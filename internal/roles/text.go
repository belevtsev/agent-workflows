package roles

import (
	"embed"
	"fmt"
	"strings"
	"unicode/utf8"
)

//go:embed text/*.md
var texts embed.FS

// Coordinator is the name of the coordinator's instructions among the
// texts.
const Coordinator = "coordinator"

// The budgets of the texts, in characters.
const (
	MaxRoleText        = 8000
	MaxCoordinatorText = 12000
	MaxAllText         = 60000
)

// Text is the one text of a role, or the coordinator's instructions.
func Text(id string) (string, error) {
	if id != Coordinator && !Known(id) {
		return "", fmt.Errorf("unknown role %q; the roles are %s", id, strings.Join(IDs(), ", "))
	}
	data, err := texts.ReadFile("text/" + id + ".md")
	if err != nil {
		return "", err
	}
	return string(data), nil
}

// TextSize is the size of a text in characters.
func TextSize(id string) int {
	text, _ := Text(id)
	return utf8.RuneCountInString(text)
}

// Skill is the skill for a daily task, in the default plugin. TeamPlugin is the
// opt-in plugin with the roles, which a host names as plugin:role; TeamRoot is
// its directory and ManagedSkill its skill with the coordinator's instructions.
const (
	Skill        = "skills/task"
	TeamPlugin   = "kitsu-team"
	TeamRoot     = "plugins/" + TeamPlugin
	ManagedSkill = TeamRoot + "/skills/managed"
)

// generated marks a file that is made from a text. A host gives the whole
// file to a model, so the mark obeys the rule of the texts: it names no
// tool of a language.
func generated(id string) string {
	return fmt.Sprintf("<!-- Generated from internal/roles/text/%s.md. Do not edit this file: a test compares it with that text. -->\n\n", id)
}

// HostFiles are the files the plugins ship, by their path from the root of
// the repository: the skill for a daily task, and in the opt-in plugin one
// file for each role and the skill with the coordinator's instructions. Each
// is made from one text, so the two cannot drift apart.
func HostFiles() (map[string]string, error) {
	files := map[string]string{}
	for _, role := range All(nil) {
		text, err := Text(role.ID)
		if err != nil {
			return nil, err
		}
		model := role.Models["claude"]
		head := fmt.Sprintf("---\nname: %s\ndescription: %s Requires a Kitsu coordinator brief.\nmodel: %s\neffort: %s\ntools: %s\n---\n",
			role.ID, role.Job, model.Model, model.Effort, strings.Join(role.Tools, ", "))
		files[TeamRoot+"/agents/"+role.ID+".md"] = head + generated(role.ID) + text
	}
	text, err := Text(Coordinator)
	if err != nil {
		return nil, err
	}
	const head = "---\nname: task\ndescription: Plan, implement, review, repair, verify or deliver a coding task from its current state in Codex or Claude Code. Use it to resume recorded work.\n---\n"
	daily, err := texts.ReadFile("text/harness.md")
	if err != nil {
		return nil, err
	}
	files[Skill+"/SKILL.md"] = head + generated("harness") + string(daily)
	files[ManagedSkill+"/SKILL.md"] = "---\nname: managed\ndescription: Coordinate a coding task through Kitsu's specialist roles, an OpenSpec change record, role settings or a supervised run. Use it only when the developer asks for it, and first say that on two small tasks it used about 5 and 39 times the tokens of a plain agent.\n---\n" + generated(Coordinator) + text
	return files, nil
}
